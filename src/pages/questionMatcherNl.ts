export function dutchToCues(text: string): string {
  let out = text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
  for (const [pattern, english] of PHRASES) out = out.replace(pattern, english);
  return out;
}
